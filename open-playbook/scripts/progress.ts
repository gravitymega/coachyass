// npm run progress : écrit PROGRESS.md (fiches terminées par catégorie, d'après le catalogue).
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import type { Library } from "../src/engine.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const lib = JSON.parse(readFileSync(join(root, "data/tactics.json"), "utf8")) as Library;
const catalogue = JSON.parse(readFileSync(join(root, "data/catalogue_500.json"), "utf8")) as {
  cat: string;
  family: string;
  status: string;
}[];

const animated = new Set(lib.tactics.filter((t) => t.steps?.length).map((t) => t.id));
const rows = lib.cats.map((c) => {
  const items = catalogue.filter((e) => e.cat === c.id);
  const done = items.filter((e) => e.status === "done").length;
  const anim = lib.tactics.filter((t) => t.cat === c.id && animated.has(t.id)).length;
  return { c, done, total: items.length, anim };
});
const done = rows.reduce((n, r) => n + r.done, 0);
const total = rows.reduce((n, r) => n + r.total, 0);
const bar = (d: number, t: number) => {
  const n = t ? Math.round((d / t) * 20) : 0;
  return "█".repeat(n) + "░".repeat(20 - n);
};

const families = new Map<string, { done: number; total: number }>();
for (const e of catalogue) {
  const k = `${e.cat} › ${e.family}`;
  const f = families.get(k) ?? { done: 0, total: 0 };
  f.total++;
  if (e.status === "done") f.done++;
  families.set(k, f);
}

const md = `# Avancement / Progress

Généré par \`npm run progress\` — ne pas modifier à la main.
Generated by \`npm run progress\` — do not edit by hand.

**${done} / ${total}** fiches terminées · cards done — ${animated.size} animées · animated — ${
  lib.tactics.filter((t) => t.review !== "approved").length
} en attente de relecture · awaiting review

| Catégorie · Category | Terminées · Done | Animées · Animated | |
|---|---:|---:|---|
${rows.map((r) => `| ${r.c.fr} · ${r.c.en} | ${r.done} / ${r.total} | ${r.anim} | \`${bar(r.done, r.total)}\` |`).join("\n")}

## Par famille · By family

| Famille · Family | Terminées · Done |
|---|---:|
${[...families].map(([k, f]) => `| ${k} | ${f.done} / ${f.total} |`).join("\n")}
`;
writeFileSync(join(root, "PROGRESS.md"), md);
console.log(`PROGRESS.md : ${done}/${total} terminées, ${animated.size} animées.`);
